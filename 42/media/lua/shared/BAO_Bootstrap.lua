-----------------------------------------------------------
-- Bandits AI Overhaul
-- BAO_Bootstrap.lua
--
-- Главная точка запуска мода.
--
-- Здесь мы:
-- 1. Создаём общую таблицу BAO.
-- 2. Объявляем функцию логирования.
-- 3. Запускаем систему фракций.
-- 4. Запускаем систему отрядов.
--
-- Важно:
-- Сначала должны появиться фракции.
-- И только после этого можно создавать отряды,
-- потому что каждый отряд принадлежит определённой фракции.
-----------------------------------------------------------


-- Project Zomboid сам предоставляет глобальную таблицу Events.
-- VS Code не знает об API игры и поэтому может показывать
-- предупреждение Undefined global Events.
---@diagnostic disable: undefined-global


-----------------------------------------------------------
-- ОБЩАЯ ТАБЛИЦА МОДА
-----------------------------------------------------------

-- Если таблица BAO уже существует, сохраняем её.
-- Если ещё не существует — создаём новую.
--
-- Благодаря этому разные файлы мода используют
-- одну общую таблицу:
--
-- BAO.Factions
-- BAO.Squads
-- BAO.Log
-- BAO.Initialize
BAO = BAO or {}


-----------------------------------------------------------
-- ВЕРСИЯ МОДА
-----------------------------------------------------------

BAO.Version = "0.1.0"


-----------------------------------------------------------
-- ФУНКЦИЯ ЛОГИРОВАНИЯ
-----------------------------------------------------------

-- Эта функция выводит сообщения в лог Project Zomboid.
--
-- Например:
--
-- BAO.Log("Hello")
--
-- В логе появится:
--
-- [BAO] Hello
--
-- tostring() превращает переданное значение в строку,
-- чтобы функция могла принимать не только текст.
function BAO.Log(message)

print("[BAO] " .. tostring(message))

end


-----------------------------------------------------------
-- ОСНОВНАЯ ИНИЦИАЛИЗАЦИЯ МОДА
-----------------------------------------------------------

-- Эта функция запускает системы нашего мода.
--
-- Она пока вызывается только один раз после запуска игры.
function BAO.Initialize()

BAO.Log("Initialization started")


-------------------------------------------------------
-- ЭТАП 1. ИНИЦИАЛИЗАЦИЯ ФРАКЦИЙ
-------------------------------------------------------

-- Проверяем, существует ли система фракций
-- и есть ли в ней функция InitializeDefaults().
--
-- Проверка нужна, чтобы мод не завершился с ошибкой,
-- если файл BAO_Factions.lua по какой-то причине
-- не загрузился.
if BAO.Factions
and BAO.Factions.InitializeDefaults then

-- Создаём стандартные фракции:
--
-- survivors
-- bandits
-- military
-- raiders
BAO.Factions.InitializeDefaults()

BAO.Log("Faction system initialized")

else

BAO.Log(
"ERROR: Faction system is not available"
)

end


-------------------------------------------------------
-- ЭТАП 2. ИНИЦИАЛИЗАЦИЯ ОТРЯДОВ
-------------------------------------------------------

-- Отряды создаются только после фракций.
--
-- Например, отряд bandit_patrol_001
-- должен принадлежать фракции bandits.
if BAO.Squads
and BAO.Squads.InitializeDefaults then

-- Создаём тестовый отряд бандитов.
BAO.Squads.InitializeDefaults()

BAO.Log("Squad system initialized")

else

BAO.Log(
"ERROR: Squad system is not available"
)

end


-------------------------------------------------------
-- ЗАВЕРШЕНИЕ ИНИЦИАЛИЗАЦИИ
-------------------------------------------------------
if BAO.NPCData
        and BAO.NPCData.InitializeDefaults then
        BAO.NPCData.InitializeDefaults()
        BAO.Log("NPC data system initialized")
    else
        BAO.Log("ERROR: NPC data system is not available")
    end

BAO.Log("Initialization finished")

end


-----------------------------------------------------------
-- ПОДКЛЮЧЕНИЕ К СОБЫТИЮ ЗАПУСКА ИГРЫ
-----------------------------------------------------------

-- OnGameBoot вызывается после загрузки игры.
--
-- Когда событие сработает, оно вызовет:
--
-- BAO.Initialize()
--
-- То есть вся цепочка будет такой:
--
-- OnGameBoot
-- ↓
-- BAO.Initialize()
-- ↓
-- BAO.Factions.InitializeDefaults()
-- ↓
-- BAO.Squads.InitializeDefaults()
if Events and Events.OnGameBoot then

Events.OnGameBoot.Add(function()

BAO.Log("OnGameBoot event received")

BAO.Initialize()

end)

else

BAO.Log(
"WARNING: OnGameBoot event is not available"
)

end


-----------------------------------------------------------
-- СООБЩЕНИЕ О ЗАГРУЗКЕ BOOTSTRAP
-----------------------------------------------------------

BAO.Log("Bootstrap loaded")